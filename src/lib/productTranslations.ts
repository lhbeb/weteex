/**
 * Resolves product translation dynamically:
 * 1. Checks product.meta.translations.en directly in the Supabase row
 * 2. Checks product.meta.[title_en / description_en] in DB
 * 3. Falls back to static dictionary
 * 4. Falls back to product.title / product.description
 */
export function getProductTranslation(
  slugOrProduct: string | { slug: string; title?: string; description?: string; brand?: string; meta?: any },
  _lang: 'en' = 'en',
  fallbackTitle?: string,
  fallbackDesc?: string
): { title: string; description: string } {
  const isObject = typeof slugOrProduct === 'object' && slugOrProduct !== null;
  const slug = isObject ? slugOrProduct.slug : slugOrProduct;
  const meta = isObject ? slugOrProduct.meta : undefined;
  const baseTitle = isObject ? slugOrProduct.title : fallbackTitle;
  const baseDesc = isObject ? slugOrProduct.description : fallbackDesc;

  // 1. Direct from Database meta.translations (if present in Supabase)
  if (meta?.translations && typeof meta.translations === 'object') {
    const dbTrans = meta.translations.en;
    if (dbTrans && dbTrans.title) {
      return {
        title: dbTrans.title,
        description: normalizeDescriptionBrand(
          dbTrans.description || baseDesc || dbTrans.title,
          isObject ? slugOrProduct.brand : undefined,
        ),
      };
    }
  }

  // 2. Direct from Database explicit English keys
  if (meta?.title_en || meta?.titleEn) {
    return {
      title: meta.title_en || meta.titleEn,
      description: normalizeDescriptionBrand(
        meta.description_en || meta.descriptionEn || baseDesc || '',
        isObject ? slugOrProduct.brand : undefined,
      ),
    };
  }

  // 3. Fallback to code dictionary
  const staticDict = PRODUCT_TRANSLATIONS[slug];
  if (staticDict?.en) {
    return staticDict.en;
  }

  // 4. Default fallback
  return {
    title: baseTitle || 'Product',
    description: baseDesc || baseTitle || '',
  };
}

function normalizeDescriptionBrand(description: string, brand?: string): string {
  const actualBrand = brand?.trim();
  if (!actualBrand || actualBrand.toLowerCase() === 'unbranded') return description;

  return description.replace(
    /((?:Brand|Marke)\s*:\s*)(?:Weteextees(?:\s*\/\s*Kollektion)?|Unbranded)/gi,
    `$1${actualBrand}`,
  );
}
